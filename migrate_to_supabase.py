"""One-time migration from the local My Closet SQLite database to Supabase.

Run from the folder containing closet.db, private_uploads/, and static/uploads/.
Required environment variables:
  DATABASE_URL
  SUPABASE_URL
  SUPABASE_SERVICE_ROLE_KEY
Optional:
  SUPABASE_BUCKET (defaults to closet-photos)

Use a brand-new/empty Supabase project for the first migration. Never share the
service-role key or database password publicly.
"""

from datetime import datetime
from pathlib import Path
import mimetypes
import os
import sqlite3
import sys

import psycopg
from psycopg.rows import dict_row
from supabase import create_client

BASE_DIR = Path(__file__).resolve().parent
SQLITE_PATH = BASE_DIR / "closet.db"
PHOTO_DIRS = [BASE_DIR / "private_uploads", BASE_DIR / "static" / "uploads"]
DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()
SUPABASE_URL = os.environ.get("SUPABASE_URL", "").strip()
SUPABASE_SERVICE_ROLE_KEY = os.environ.get("SUPABASE_SERVICE_ROLE_KEY", "").strip()
BUCKET = os.environ.get("SUPABASE_BUCKET", "closet-photos").strip()


def require_config():
    missing = [name for name, value in [
        ("DATABASE_URL", DATABASE_URL),
        ("SUPABASE_URL", SUPABASE_URL),
        ("SUPABASE_SERVICE_ROLE_KEY", SUPABASE_SERVICE_ROLE_KEY),
    ] if not value]
    if missing:
        print("環境変数が設定されていません: " + ", ".join(missing))
        print("秘密情報をチャットに貼らず、PowerShell の環境変数として設定してください。")
        sys.exit(1)
    if not SQLITE_PATH.is_file():
        print(f"{SQLITE_PATH} が見つかりません。既存の closet.db がある fashionista フォルダで実行してください。")
        sys.exit(1)


def timestamp_value(value):
    if value is None or value == "":
        return None
    if isinstance(value, datetime):
        return value
    try:
        return datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    except ValueError:
        return None


def table_exists(conn, table_name):
    row = conn.execute(
        "SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (table_name,)
    ).fetchone()
    return row is not None


def local_rows(conn, table):
    if not table_exists(conn, table):
        return []
    conn.row_factory = sqlite3.Row
    return [dict(row) for row in conn.execute(f'SELECT * FROM "{table}"').fetchall()]


def find_photo(image_value):
    filename = Path(str(image_value)).name
    for folder in PHOTO_DIRS:
        candidate = folder / filename
        if candidate.is_file():
            return filename, candidate
    return filename, None


def create_schema(conn):
    statements = [
        """CREATE TABLE IF NOT EXISTS users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id TEXT NOT NULL UNIQUE,
            password_hash TEXT NOT NULL,
            view_password_hash TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )""",
        """CREATE TABLE IF NOT EXISTS clothing_items (
            id TEXT PRIMARY KEY,
            title TEXT NOT NULL,
            image TEXT NOT NULL,
            owner_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )""",
        """CREATE TABLE IF NOT EXISTS outfits (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            outfit_date TEXT NOT NULL,
            caption TEXT NOT NULL DEFAULT '',
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            UNIQUE(owner_id, outfit_date)
        )""",
        """CREATE TABLE IF NOT EXISTS outfit_items (
            outfit_id BIGINT NOT NULL REFERENCES outfits(id) ON DELETE CASCADE,
            item_id TEXT NOT NULL REFERENCES clothing_items(id) ON DELETE CASCADE,
            position INTEGER NOT NULL DEFAULT 0,
            PRIMARY KEY(outfit_id, item_id)
        )""",
        """CREATE TABLE IF NOT EXISTS outfit_ratings (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            outfit_id BIGINT NOT NULL REFERENCES outfits(id) ON DELETE CASCADE,
            user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            stars INTEGER NOT NULL CHECK(stars BETWEEN 1 AND 5),
            comment TEXT NOT NULL DEFAULT '',
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            UNIQUE(outfit_id, user_id)
        )""",
    ]
    for statement in statements:
        conn.execute(statement)


def main():
    require_config()
    supabase = create_client(SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY)
    storage = supabase.storage.from_(BUCKET)

    with sqlite3.connect(SQLITE_PATH) as local:
        local.row_factory = sqlite3.Row
        users = local_rows(local, "users")
        clothes = local_rows(local, "clothing_items")
        outfits = local_rows(local, "outfits")
        outfit_items = local_rows(local, "outfit_items")
        ratings = local_rows(local, "outfit_ratings")

        # Check every referenced local photo before changing the cloud database.
        photo_files = {}
        missing = []
        for item in clothes:
            filename, path = find_photo(item.get("image", ""))
            if path is None:
                missing.append(filename)
            else:
                photo_files[filename] = path
        if missing:
            print("次の写真がローカルの写真フォルダに見つからないため、移行を中止しました:")
            for filename in sorted(set(missing)):
                print(" - " + filename)
            print("private_uploads または static/uploads の写真を確認してください。データはまだ移行していません。")
            sys.exit(2)

        cloud_url = DATABASE_URL
        if cloud_url.startswith("postgres://"):
            cloud_url = "postgresql://" + cloud_url[len("postgres://"):]
        if "sslmode=" not in cloud_url:
            cloud_url += "&sslmode=require" if "?" in cloud_url else "?sslmode=require"
        with psycopg.connect(cloud_url, row_factory=dict_row) as cloud:
            create_schema(cloud)
            cloud.commit()

            # Upload photos into the private Supabase Storage bucket.
            for filename, path in photo_files.items():
                content_type = mimetypes.guess_type(filename)[0] or "application/octet-stream"
                with path.open("rb") as image_file:
                    storage.upload(
                        path=filename,
                        file=image_file.read(),
                        file_options={"content-type": content_type, "upsert": "true"},
                    )
            print(f"写真 {len(photo_files)} 枚をクラウドにアップロードしました。")

            # Copy tables in dependency order, preserving IDs so relationships survive.
            for row in users:
                cloud.execute(
                    """INSERT INTO users (id,user_id,password_hash,view_password_hash,created_at)
                       VALUES (%s,%s,%s,%s,%s) ON CONFLICT (id) DO NOTHING""",
                    (row["id"], row["user_id"], row["password_hash"],
                     row.get("view_password_hash"), timestamp_value(row.get("created_at"))),
                )
            for row in clothes:
                cloud.execute(
                    """INSERT INTO clothing_items (id,title,image,owner_id,created_at)
                       VALUES (%s,%s,%s,%s,%s) ON CONFLICT (id) DO NOTHING""",
                    (row["id"], row["title"], Path(str(row["image"])).name,
                     row.get("owner_id"), timestamp_value(row.get("created_at"))),
                )
            for row in outfits:
                cloud.execute(
                    """INSERT INTO outfits (id,owner_id,outfit_date,caption,created_at,updated_at)
                       VALUES (%s,%s,%s,%s,%s,%s) ON CONFLICT (id) DO NOTHING""",
                    (row["id"], row["owner_id"], row["outfit_date"], row.get("caption", ""),
                     timestamp_value(row.get("created_at")), timestamp_value(row.get("updated_at"))),
                )
            for row in outfit_items:
                cloud.execute(
                    """INSERT INTO outfit_items (outfit_id,item_id,position)
                       VALUES (%s,%s,%s) ON CONFLICT (outfit_id,item_id) DO NOTHING""",
                    (row["outfit_id"], row["item_id"], row.get("position", 0)),
                )
            for row in ratings:
                cloud.execute(
                    """INSERT INTO outfit_ratings (id,outfit_id,user_id,stars,comment,created_at,updated_at)
                       VALUES (%s,%s,%s,%s,%s,%s,%s) ON CONFLICT (id) DO NOTHING""",
                    (row["id"], row["outfit_id"], row["user_id"], row["stars"], row.get("comment", ""),
                     timestamp_value(row.get("created_at")), timestamp_value(row.get("updated_at"))),
                )

            # Advance identity sequences beyond the IDs copied from SQLite.
            for table in ("users", "outfits", "outfit_ratings"):
                max_row = cloud.execute(f"SELECT MAX(id) AS max_id FROM {table}").fetchone()
                max_id = max_row["max_id"]
                if max_id is not None:
                    cloud.execute(
                        "SELECT setval(pg_get_serial_sequence(%s, 'id'), %s, true)",
                        (f"public.{table}", max_id),
                    )
            cloud.commit()

    print("移行が完了しました。")
    print(f"アカウント: {len(users)}、服: {len(clothes)}、コーデ: {len(outfits)}、評価: {len(ratings)}")
    print("次に app.py を Supabase 接続設定で起動し、画面でデータを確認してください。")
    print("既存の closet.db と写真フォルダは、確認が終わるまで削除しないでください。")


if __name__ == "__main__":
    main()
